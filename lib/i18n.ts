export const DICTS: Record<Lang, Dict> = { en, ru, zh, es };
export const LANG_LABELS: Record<Lang, string> = { en: 'EN', ru: 'RU', zh: 'CN', es: 'ES' };

export function t(lang: Lang, key: Key, vars?: Record<string, string | number>): string {
  let s: string = DICTS[lang]?.[key] ?? en[key];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function relTime(lang: Lang, at: number, now = Date.now()): string {
  const m = Math.floor((now - at) / 60000);
  if (m < 1) return t(lang, 'time.now');
  if (m < 60) return t(lang, 'time.min', { n: m });
  const h = Math.floor(m / 60);
  if (h < 24) return t(lang, 'time.h', { n: h });
  return t(lang, 'time.d', { n: Math.floor(h / 24) });
}
